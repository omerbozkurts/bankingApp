import time
from collections import deque


class SlidingWindowLimiter:
    """In-process sliding-window limiter keyed by client IP.

    Good enough for a single API process. With several workers or servers, move this to the
    reverse proxy or a shared store (e.g. Redis), otherwise each process counts separately.
    """

    def __init__(self, max_requests: int, window_seconds: float) -> None:
        self.max_requests = max_requests
        self.window_seconds = window_seconds
        self._hits: dict[str, deque[float]] = {}

    def allow(self, key: str) -> bool:
        now = time.monotonic()
        hits = self._hits.setdefault(key, deque())
        while hits and now - hits[0] >= self.window_seconds:
            hits.popleft()
        if len(hits) >= self.max_requests:
            return False
        hits.append(now)
        return True

    def reset(self) -> None:
        self._hits.clear()
