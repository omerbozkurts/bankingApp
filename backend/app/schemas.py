from datetime import date, datetime
from typing import Annotated, Literal

from pydantic import AfterValidator, BaseModel, ConfigDict, Field, StrictInt, model_validator

from app.banking import is_valid_national_id, is_valid_tr_iban, normalize_iban


class LoginRequest(BaseModel):
    # Same rules as the app and the legacy desktop version: 9-digit customer no, 6-digit password.
    customer_no: str = Field(pattern=r"^[0-9]{9}$", examples=["123456789"])
    password: str = Field(pattern=r"^[0-9]{6}$", examples=["123456"])


class Token(BaseModel):
    # Omitted for web (cookie) logins so page JavaScript never sees the session JWT.
    access_token: str | None = None
    token_type: Literal["bearer", "cookie"] = "bearer"
    expires_in: int


def _iban(value: str) -> str:
    iban = normalize_iban(value)
    if not is_valid_tr_iban(iban):
        raise ValueError("Geçerli bir TR IBAN girin.")
    return iban


def _national_id(value: str) -> str:
    if not is_valid_national_id(value):
        raise ValueError("T.C. kimlik numarası geçersiz.")
    return value


def _full_name(value: str) -> str:
    name = " ".join(value.split())
    if len(name) < 3 or not all(part.isalpha() for part in name.split()):
        raise ValueError("Ad soyad yalnızca harflerden oluşmalı.")
    return name


def _adult_birth_date(value: date) -> date:
    today = date.today()
    age = today.year - value.year - ((today.month, today.day) < (value.month, value.day))
    if value > today or age > 120:
        raise ValueError("Doğum tarihi geçersiz.")
    if age < 18:
        raise ValueError("Hesap açmak için 18 yaşından büyük olmalısınız.")
    return value


def _new_password(value: str) -> str:
    # Six digits is a small space already; refuse the guesses people try first.
    if len(set(value)) == 1 or value in "0123456789" or value in "9876543210":
        raise ValueError("Tahmin edilmesi kolay bir şifre seçmeyin (111111, 123456 gibi).")
    return value


Iban = Annotated[str, AfterValidator(_iban)]


class RegisterRequest(BaseModel):
    national_id: Annotated[str, Field(pattern=r"^[0-9]{11}$"), AfterValidator(_national_id)]
    full_name: Annotated[str, Field(max_length=120), AfterValidator(_full_name)]
    birth_date: Annotated[date, AfterValidator(_adult_birth_date)]
    password: Annotated[str, Field(pattern=r"^[0-9]{6}$"), AfterValidator(_new_password)]


class RegisterOut(BaseModel):
    customer_no: str
    full_name: str


class CustomerOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    customer_no: str
    full_name: str
    is_admin: bool


class AccountOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    kind: Literal["checking", "savings", "credit"]
    name: str
    iban: str
    # Negative on a credit account: the amount owed.
    balance_kurus: int
    goal_kurus: int | None
    credit_limit_kurus: int | None
    frozen: bool


class OpenAccountRequest(BaseModel):
    kind: Literal["checking", "savings", "credit"]
    name: Annotated[str, Field(min_length=1, max_length=80), AfterValidator(str.strip)]
    goal_kurus: int | None = Field(default=None, gt=0, le=100_000_000_000)

    @model_validator(mode="after")
    def goal_only_for_savings(self) -> OpenAccountRequest:
        if not self.name:
            raise ValueError("Hesap adı boş olamaz.")
        if self.kind != "savings" and self.goal_kurus is not None:
            raise ValueError("Birikim hedefi yalnızca birikim hesaplarında belirlenebilir.")
        return self


class TransactionOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: int
    amount_kurus: int
    balance_after_kurus: int | None
    description: str
    counterparty: str | None
    created_at: datetime


class TransactionPage(BaseModel):
    items: list[TransactionOut]
    # Pass as `before_id` to get the next (older) page; null when there are no more.
    next_before_id: int | None


class RecipientOut(BaseModel):
    iban: str
    masked_name: str


# Account ids are PostgreSQL integers; larger values would fail in the driver with a 500.
DbId = Annotated[int, Field(ge=1, le=2**31 - 1)]


class TransferRequest(BaseModel):
    from_account_id: DbId
    to_iban: Iban
    # Strict: lax mode would accept true as 1 kuruş and "100" as 100.
    amount_kurus: StrictInt = Field(gt=0)
    description: Annotated[str, Field(max_length=140), AfterValidator(str.strip)] = ""
    # Generated by the client per transfer attempt; resending it never pays twice.
    idempotency_key: str = Field(pattern=r"^[A-Za-z0-9-]{8,64}$")


class TransferOut(BaseModel):
    id: int
    from_account_id: int
    to_iban: str
    recipient: str
    amount_kurus: int
    description: str
    from_balance_after_kurus: int
    created_at: datetime


class AssistantMessage(BaseModel):
    role: Literal["user", "assistant"]
    # Assistant replies come back as history and may be longer than what a customer may type.
    content: Annotated[str, Field(min_length=1, max_length=20_000), AfterValidator(str.strip)]

    @model_validator(mode="after")
    def user_message_length(self) -> AssistantMessage:
        if self.role == "user" and len(self.content) > 2000:
            raise ValueError("Mesaj en fazla 2000 karakter olabilir.")
        return self


class AssistantRequest(BaseModel):
    # The client keeps the conversation and sends it whole; the API stores nothing.
    messages: Annotated[list[AssistantMessage], Field(min_length=1, max_length=20)]

    @model_validator(mode="after")
    def ends_with_user(self) -> AssistantRequest:
        if any(not m.content for m in self.messages):
            raise ValueError("Mesaj boş olamaz.")
        if self.messages[0].role != "user" or self.messages[-1].role != "user":
            raise ValueError("Konuşma müşteri mesajıyla başlamalı ve bitmeli.")
        return self


class AssistantReply(BaseModel):
    reply: str


class AdminCustomerOut(BaseModel):
    id: int
    customer_no: str
    full_name: str
    is_admin: bool
    # Temporarily locked after repeated wrong passwords.
    locked: bool
    account_count: int
    created_at: datetime


class AdminCustomerPage(BaseModel):
    items: list[AdminCustomerOut]
    next_before_id: int | None


class AdminCustomerDetail(AdminCustomerOut):
    accounts: list[AccountOut]


class AdminActionRequest(BaseModel):
    # Every change is logged with a reason someone can read later.
    reason: Annotated[str, Field(max_length=200), AfterValidator(str.strip)]

    @model_validator(mode="after")
    def reason_given(self) -> AdminActionRequest:
        if len(self.reason) < 3:
            raise ValueError("Bir açıklama yazın (en az 3 karakter).")
        return self


class AdminActionOut(BaseModel):
    id: int
    action: Literal[
        "freeze_account", "unfreeze_account", "unlock_customer", "grant_admin", "revoke_admin"
    ]
    # Null when the change was made on the server (granting or revoking admin rights).
    admin_customer_no: str | None
    customer_no: str
    account_id: int | None
    reason: str
    created_at: datetime


class AdminActionPage(BaseModel):
    items: list[AdminActionOut]
    next_before_id: int | None
